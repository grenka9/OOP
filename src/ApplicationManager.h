#pragma once
#include <random>
#include <string>

#include "ConsoleSystem.h"

// Управляет работой приложения: обработкой ввода,
// настройкой параметров анимации и завершением программы.
class ApplicationManager {
private:
    // Объект для выполнения операций с консолью.
    ConsoleSystem console;
    // Генератор случайных чисел для выбора символов, цветов и позиций.
    std::mt19937 generator{std::random_device{}()};

    // Текущая скорость движения линии.
    int speed = 10;
    // Текущая длина линии.
    int length = 10;
    // Показывает, включен ли режим случайного изменения цветов.
    bool epilepsyMode = false;

    // Преобразует строку в целое число и проверяет отсутствие лишних символов.
    bool parseNumber(const std::string& text, int& result);
    // Считывает целое число и проверяет, входит ли оно в допустимый диапазон.
    int readNumber(const std::string& prompt, int minValue, int maxValue);
    // Считывает и проверяет выбор пользователя для режима случайного изменения цветов.
    bool readEpilepsyMode();
    // Запрашивает у пользователя все параметры анимации в диалоговом режиме.
    void interactiveInput();
    // Обрабатывает аргументы командной строки или запускает диалоговый ввод.
    // Возвращает false, если аргументы некорректны или запрошена справка.
    bool parseArguments(int argc, char* argv[]);

public:
    // Выводит справочную информацию о запуске программы и доступных параметрах.
    static void printHelp();
    // Запускает приложение: обрабатывает ввод, выполняет анимацию,
    // отслеживает нажатие клавиши выхода и восстанавливает состояние консоли.
    int run(int argc, char* argv[]);
};
