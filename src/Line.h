#pragma once
#include <random>

class ConsoleSystem;

// Представляет вертикальную линию из случайно генерируемых символов.
// Управляет движением линии, ее длиной, скоростью и цветовым режимом.
class Line {
private:
    // Горизонтальная координата расположения линии в консоли.
    int x;
    // Количество символов в линии.
    int length;
    // Скорость движения линии в символах за секунду.
    int speed;
    // Цвет всей линии, используемый при отключенном режиме случайного цвета каждого символа.
    int lineColor;
    // Показывает, включен ли режим случайного изменения цветов.
    bool epilepsyMode;
    // Ссылка на генератор случайных чисел приложения.
    std::mt19937& generator;

    // Генерирует случайный цвет консоли.
    int randomColor();
    // Генерирует случайный символ из заранее заданного набора.
    char randomSymbol();

public:
    // Инициализирует параметры линии и задает ее цвет.
    Line(int positionX, int lineLength, int lineSpeed,
         bool epilepsy, std::mt19937& rng);

    // Выполняет анимацию движения линии снизу вверх.
    // В начале линии генерируются новые символы, а в конце стираются старые.
    // Возвращает false, если пользователь нажал клавишу Esc.
    bool crawl(ConsoleSystem& console);
};
