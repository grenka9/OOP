#pragma once
#include <windows.h>

// Предоставляет методы для работы с консолью Windows:
// перемещение курсора, изменение цвета текста, очистка экрана и получение размеров окна.
class ConsoleSystem {
private:
    // Дескриптор стандартного потока вывода консоли.
    HANDLE output;

public:
     // Получает дескриптор стандартного потока вывода консоли.
    ConsoleSystem();

    // Скрывает курсор консоли на время анимации.
    void hideCursor();
    // Снова делает курсор консоли видимым.
    void showCursor();
    // Перемещает курсор в заданные координаты консоли.
    void moveCursor(int x, int y);
    // Устанавливает цвет последующего выводимого текста.
    void setColor(int color);
    // Очищает экран консоли и восстанавливает стандартный цвет текста.
    void clearScreen();
    // Возвращает ширину видимой области консоли в символах.
    int getWidth();
    // Возвращает высоту видимой области консоли в символах.
    int getHeight();
};
